"""Generate AppHtml/RDCFlexTron/ftglyphs.css from AppSrc/FTDashIcons.pkg: every DashIcon glyph as a CSS class,
"ftg-<name>", that draws the glyph in front of a web button's caption, or of a cFTHtmlPage's title.

Run it after adding or changing a glyph in FTDashIcons.pkg, and commit both files:

    python Tools/MakeFTGlyphsCss.py

WHY A CLASS: the Studio's Designer draws a web button with the framework's own script and runs none of ours,
so a glyph set with psGlyph shows only when the program runs. What the Designer does apply is an object's
literal psCSSClass, styled by the program's application.css - which imports this sheet. So a button named
"ftbtn ftg-exit" shows its glyph in the Designer as in the program (and cFTWebButton turns a psGlyph NAME
into the same class when the program runs).

HOW THE GLYPHS ARE READ - the way DashIcon returns them: a branch that moves a path into sD is that path in
the function's shared <svg> template (its last Function_Return); a branch that returns an <svg> of its own
is taken whole. A one-colour glyph (currentColor) becomes a MASK painted in the button's text colour, so it
follows the theme; a glyph with its own rgb() fills and no currentColor is a background image in its own
colours. The classes come in the order of the CS_Glyph* Defines.

It also checks FTGlyphNames, the list of every glyph's name: it must hold each CS_Glyph* Define once.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PKG = os.path.join(ROOT, 'AppSrc', 'FTDashIcons.pkg')
OUT = os.path.join(ROOT, 'AppHtml', 'RDCFlexTron', 'ftglyphs.css')


def check_glyph_names(lines, constants):
    """FTGlyphNames lists every glyph by its constant; a glyph left out of it never reaches a picker."""
    start = next((i for i, line in enumerate(lines) if re.match(r'\s*Function\s+FTGlyphNames\s+Global\b', line)), None)
    if start is None:
        sys.exit('FTGlyphNames: not found')
    end = next(i for i in range(start, len(lines)) if re.match(r'\s*End_Function\b', lines[i]))
    listed = [m.group(1) for m in (re.match(r'\s*Move\s+(CS_Glyph\w+)\s+to\s+asNames\b', line)
                                   for line in lines[start:end]) if m]
    missing = [c for c in constants if c not in listed]
    twice = sorted(set(c for c in listed if listed.count(c) > 1))
    unknown = [c for c in listed if c not in constants]
    if missing or twice or unknown:
        sys.exit('FTGlyphNames and the CS_Glyph* Defines disagree - not listed: %s; listed twice: %s; no Define: %s'
                 % (missing, twice, unknown))


def read_glyphs():
    lines = open(PKG, 'rb').read().decode('utf-8-sig').splitlines()
    names, order = {}, []
    for line in lines:
        m = re.match(r'\s*Define\s+(CS_Glyph\w+)\s+for\s+"([^"]+)"', line)
        if m:
            names[m.group(1)] = m.group(2)
            order.append(m.group(2))
    check_glyph_names(lines, list(names))

    start = next(i for i, line in enumerate(lines) if re.match(r'\s*Function\s+DashIcon\s+Global\b', line))
    end = next(i for i in range(start, len(lines)) if re.match(r'\s*End_Function\b', lines[i]))
    body = lines[start:end]

    template = [line for line in body if '+ sD +' in line]
    if len(template) != 1:
        sys.exit('DashIcon: expected one shared template (a Function_Return with + sD +), found %d' % len(template))
    m = re.search(r"Function_Return \('(.*)' \+ sD \+ '(.*)'\)\s*$", template[0])
    prefix, suffix = m.group(1), m.group(2)

    svgs = {}
    for i, line in enumerate(body):
        m = re.match(r'\s*If \(sName = (CS_Glyph\w+|"[^"]+")\) ;\s*$', line)
        if not m:
            continue
        key = m.group(1)
        name = key.strip('"') if key.startswith('"') else names[key]
        nxt = body[i + 1]
        mm = re.match(r'\s*Move "([^"]*)" to sD\s*$', nxt)
        if mm:
            svgs[name] = prefix + mm.group(1) + suffix
            continue
        mm = re.match(r"\s*Function_Return \(?'(<svg.*</svg>)'\)?\s*$", nxt)
        if not mm:
            sys.exit('DashIcon: cannot read the branch for "%s": %s' % (name, nxt.strip()[:80]))
        svgs[name] = mm.group(1)

    missing = [n for n in order if n not in svgs]
    extra = [n for n in svgs if n not in order]
    if missing or extra:
        sys.exit('DashIcon and the CS_Glyph* Defines disagree - no branch for %s; no Define for %s' % (missing, extra))
    return [(n, svgs[n]) for n in order]


def data_uri(svg):
    s = svg.replace('<svg ', '<svg xmlns="http://www.w3.org/2000/svg" ', 1).replace('"', "'")
    for a, b in (('%', '%25'), ('<', '%3C'), ('>', '%3E'), ('#', '%23'), ('\n', ' ')):
        s = s.replace(a, b)
    return 'url("data:image/svg+xml,' + s + '")'


def two_tone(svg):
    return 'rgb(' in svg and 'currentColor' not in svg


def css(glyphs):
    head = """/* RDCFlexTron - ftglyphs.css: the DashIcon glyphs as CSS classes, for web buttons and page titles. GENERATED by
   Tools/MakeFTGlyphsCss.py from AppSrc/FTDashIcons.pkg (%d glyphs) - do not edit by hand; run the script
   after adding or changing a glyph.

   A button's glyph is drawn in front of its caption, 15 px, with the FT button's 6 px gap: "ftbtn ftg-exit",
   or psGlyph "exit", which cFTWebButton turns into the same class. A cFTHtmlPage's glyph is drawn in front
   of its title (the control's label), 26 px: "ftpage ftg-listcheck", or psTitleIcon. A class is the one thing of ours the
   Studio's Designer applies (it runs none of our code, but loads application.css, which imports this
   sheet), so the Designer shows the glyph as the running program does. One-colour glyphs are masks painted
   in the button's text colour, so they follow the theme; two-tone glyphs keep their own colours. */
.WebControl.WebButton[class*="ftg-"] button::before {
    content: "";
    flex: none;
    width: 15px;
    height: 15px;
    margin: 0;                          /* the Material theme gives button::before 8 px margins */
    background-color: currentColor;     /* the ink a mask paints with */
}
.WebControl.WebHtmlBox[class*="ftg-"] > .WebCon_Inner > label::before {
    content: "";
    flex: none;
    width: 26px;
    height: 26px;
    margin: 0;
    background-color: currentColor;
}
""" % len(glyphs)
    rules = []
    for name, svg in glyphs:
        sel = ('.WebControl.WebButton.ftg-%s button::before, .WebControl.WebHtmlBox.ftg-%s > .WebCon_Inner > label::before'
               % (name, name))
        if two_tone(svg):
            rules.append('%s { background: %s center / contain no-repeat; }' % (sel, data_uri(svg)))
        else:
            m = data_uri(svg.replace('currentColor', 'black'))
            rules.append('%s { -webkit-mask: %s center / contain no-repeat; mask: %s center / contain no-repeat; }'
                         % (sel, m, m))
    text = head + '\n'.join(rules) + '\n'
    # a two-tone glyph paints an image, not the ink
    text += ''.join(('.WebControl.WebButton.ftg-%s button::before, .WebControl.WebHtmlBox.ftg-%s > .WebCon_Inner > '
                     'label::before { background-color: transparent; }\n') % (n, n)
                    for n, s in glyphs if two_tone(s))
    return text


if __name__ == '__main__':
    glyphs = read_glyphs()
    text = css(glyphs)
    text.encode('ascii')                 # a data URI is ASCII; a stray character would be a bug
    open(OUT, 'wb').write(text.replace('\n', '\r\n').encode('ascii'))
    print('%s: %d glyph classes' % (os.path.relpath(OUT, ROOT), len(glyphs)))
